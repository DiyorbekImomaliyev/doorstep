"""Train the delivery-risk model (RK-01..03): `make risk-model`.

Writes app/ai/models/risk_v1.json (+ .meta.json), evals/risk_report.md and
evals/risk_calibration.svg. Deterministic: the same seed gives the same model.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.ai.risk import MODEL_DIR, MODEL_NAME, save_meta  # noqa: E402
from app.ai.risk_train import train  # noqa: E402
from tuning import engine_config as cfg  # noqa: E402

_SMALL = 'font-size="10"'


def calibration_svg(rows: list[dict[str, float]]) -> str:
    """A reliability diagram as plain SVG (no plotting library)."""
    size, pad = 360, 48
    top = max(max(r["mean_predicted"] for r in rows), max(r["observed_rate"] for r in rows))
    top = max(0.05, round(top * 1.15, 2))

    def xy(px: float, py: float) -> tuple[float, float]:
        span = size - 2 * pad
        return pad + px / top * span, size - pad - py / top * span

    x0, y0 = xy(0, 0)
    x1, y1 = xy(top, top)
    dots = "".join(
        '<circle cx="{:.1f}" cy="{:.1f}" r="4" fill="#0f5f5c"/>'.format(
            *xy(r["mean_predicted"], r["observed_rate"])
        )
        for r in rows
    )
    path = " ".join(
        "{}{:.1f},{:.1f}".format(
            "M" if i == 0 else "L", *xy(r["mean_predicted"], r["observed_rate"])
        )
        for i, r in enumerate(rows)
    )
    ticks = ""
    for k in range(5):
        v = top * k / 4
        tx, ty = xy(v, 0)
        lx, ly = xy(0, v)
        label = f"{v:.0%}"
        ticks += (
            f'<text x="{tx:.1f}" y="{ty + 16:.1f}" {_SMALL} text-anchor="middle">{label}</text>'
        )
        ticks += (
            f'<text x="{lx - 6:.1f}" y="{ly + 3:.1f}" {_SMALL} text-anchor="end">{label}</text>'
        )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'font-family="system-ui, sans-serif" fill="#1f2933">'
        f'<rect width="{size}" height="{size}" fill="#fff"/>'
        f'<text x="{size / 2}" y="22" font-size="13" text-anchor="middle" font-weight="600">'
        f"Risk model calibration (test split)</text>"
        f'<line x1="{x0}" y1="{y0}" x2="{x1:.1f}" y2="{y0}" stroke="#9aa5b1"/>'
        f'<line x1="{x0}" y1="{y0}" x2="{x0}" y2="{y1:.1f}" stroke="#9aa5b1"/>'
        f'<line x1="{x0}" y1="{y0}" x2="{x1:.1f}" y2="{y1:.1f}" stroke="#c3cad3" '
        f'stroke-dasharray="4 4"/>'
        f'<path d="{path}" fill="none" stroke="#0f5f5c" stroke-width="1.5"/>{dots}{ticks}'
        f'<text x="{size / 2}" y="{size - 8}" font-size="11" text-anchor="middle">'
        f"Predicted risk</text>"
        f'<text x="14" y="{size / 2}" font-size="11" text-anchor="middle" '
        f'transform="rotate(-90 14 {size / 2})">Observed failure rate</text></svg>\n'
    )


def report(meta: dict) -> str:
    m = meta["metrics"]
    lines = [
        "# Risk model report (RK-01)",
        "",
        "Generated by `make risk-model` (scripts/train_risk.py). Trained on **synthetic data**",
        "seeded from published rates; see docs/MODEL_CARD_risk.md. Production retrains on each",
        "seller's own outcomes.",
        "",
        "| Metric (held-out test split) | Value |",
        "| --- | --- |",
        f"| Orders: train / validation / test | {m['n_train']:,} / {m['n_validation']:,} / "
        f"{m['n_test']:,} |",
        f"| Failure base rate | {m['base_rate_test']:.2%} |",
        f"| PR-AUC (average precision) | {m['pr_auc_test']:.3f} |",
        f"| PR-AUC of the true synthetic probabilities (ceiling) | {m['pr_auc_oracle_test']:.3f} |",
        f"| Brier score | {m['brier_test']:.4f} |",
        f"| Expected calibration error (10 equal-count bins) | {m['ece_test']:.4f} |",
        f"| Trees | {meta['rounds']} |",
        "",
        "PR-AUC is the right headline for a rare event: a random score would get the base rate.",
        "The ceiling row shows the best any model could do on this synthetic data, since the",
        "labels are random draws from known probabilities.",
        "",
        "## Calibration",
        "",
        "Platt scaling fitted on the validation split. Mean predicted risk vs observed rate per",
        "bin (test split):",
        "",
        "![Calibration plot](risk_calibration.svg)",
        "",
        "| Bin | Mean predicted | Observed | Orders |",
        "| --- | --- | --- | --- |",
    ]
    for i, r in enumerate(meta["reliability_test"], 1):
        lines.append(
            f"| {i} | {r['mean_predicted']:.2%} | {r['observed_rate']:.2%} | {r['count']:,} |"
        )
    lines += [
        "",
        "## Reasons",
        "",
        "Each score carries its top three exact TreeSHAP contributions (XGBoost",
        '`pred_contribs`) in plain words, e.g. "Doorstep delivery instead of a locker raises the',
        'risk". Monotone constraints keep every reason pointing the sensible way.',
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    booster, meta = train(
        dict(cfg.RISK_MODEL_PARAMS),
        cfg.RISK_MODEL_ROUNDS,
        cfg.RISK_MODEL_TRAIN_ROWS,
        cfg.RISK_MODEL_SEED,
    )
    MODEL_DIR.mkdir(parents=True, exist_ok=True)
    booster.save_model(str(MODEL_DIR / f"{MODEL_NAME}.json"))
    save_meta(MODEL_DIR / f"{MODEL_NAME}.meta.json", meta)
    evals = ROOT / "evals"
    (evals / "risk_report.md").write_text(report(meta), encoding="utf-8")
    (evals / "risk_calibration.svg").write_text(
        calibration_svg(meta["reliability_test"]), encoding="utf-8"
    )
    m = meta["metrics"]
    print(
        f"risk_v1: {meta['rounds']} trees, PR-AUC {m['pr_auc_test']:.3f} "
        f"(ceiling {m['pr_auc_oracle_test']:.3f}, base rate {m['base_rate_test']:.2%}), "
        f"ECE {m['ece_test']:.4f}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
