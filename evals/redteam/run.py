"""Run the SE-03 red-team and write evals/results/se_03.json.

    uv run --env-file .env python -m evals.redteam.run            # replay, ask only new prompts
    uv run --env-file .env python -m evals.redteam.run --promptfoo-cases   # rewrite cases.yaml

Recorded answers are replayed. A prompt with no recording is asked once on EVAL_LLM_PROVIDER,
with a pause between live calls for the free tier's rate limit. EVAL_LLM_FALLBACK_PROVIDER opts in
to the paid key while the free tier is down, capped by EVAL_PAID_PROMPT_LIMIT.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from typing import Any

import yaml

from evals.recording import Recorder, eval_model
from evals.redteam.harness import HERE, RECORDINGS, RedTeam, probes, summary

RESULTS = HERE.parent / "results" / "se_03.json"
PROMPTFOO_CASES = HERE / "cases.yaml"


def promptfoo_cases() -> str:
    """The Promptfoo test list: one test per probe; the provider looks the attack up by id."""
    rows = [
        {
            "description": p.name,
            "vars": {"attack": p.attack.id, "scenario": p.scenario},
            "metadata": {"kind": p.attack.kind},
        }
        for p in probes()
    ]
    header = "# Generated by `python -m evals.redteam.run --promptfoo-cases`. Do not edit.\n"
    return header + yaml.safe_dump(rows, sort_keys=False, allow_unicode=True)


def run(delay_s: float) -> dict[str, Any]:
    recorder = Recorder(eval_model(), RECORDINGS, delay_s=delay_s)
    team = RedTeam(recorder)
    results = [team.run(p) for p in probes()]
    out = summary(results)
    out["live_calls"], out["replayed"] = recorder.asked, recorder.replayed
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--promptfoo-cases", action="store_true", help="rewrite cases.yaml")
    parser.add_argument(
        "--delay", type=float, default=float(os.environ.get("REDTEAM_DELAY_S", "4"))
    )
    args = parser.parse_args(argv)
    if args.promptfoo_cases:
        PROMPTFOO_CASES.write_text(promptfoo_cases(), encoding="utf-8")
        print(f"wrote {PROMPTFOO_CASES}")
        return 0
    out = run(args.delay)
    RESULTS.parent.mkdir(parents=True, exist_ok=True)
    RESULTS.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    keys = ("probes", "blocked", "answered", "fail", "not_run", "live_calls", "replayed")
    print(" ".join(f"{k}={out[k]}" for k in keys))
    for row in out["results"]:
        if row["status"] in ("fail", "not_run"):
            print(f"  {row['status']}: {row['probe']}: {'; '.join(row['problems'])}")
    return 0 if out["fail"] == 0 and out["not_run"] == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
